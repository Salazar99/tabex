def test_worked_example_matches_EXAMPLE_md():
    """The pair EXAMPLE.md walks through, end to end.

    EXAMPLE.md and figures/example/*.png are generated by plot_pipeline.py and
    quote these three numbers throughout. plot_pipeline.py checks its own
    arithmetic against the metric, but nothing stops the metric itself from
    moving and leaving the committed document describing a score the code no
    longer produces. This is that check.

    phi = G[0,1](x>0) && F[0,1](y<3)   theta = (x>0) U[0,1] (y<3)

    phi is strictly contained in theta: theta's u=0 disjunct discharges the
    until at instant 0 and leaves x@t1 free, while phi's G[0,1] requires x>0
    there regardless. So the forward direction is exact (every canonical cell
    of phi is also one of theta) and the backward one is not.
    """
    phi = "G[0,1](x>0) && F[0,1](y<3)"
    theta = "(x>0) U[0,1] (y<3)"
    paths1, paths2, all_vars = signal_spaces_from_definition(phi, theta)
    assert all_vars == ["x", "y"]

    D = resolve_D(None, parse(phi), parse(theta))
    assert D == 4                      # max|con(phi) u con(theta)| + 1 = 3 + 1

    volume1, volume2 = build_aligned_volumes(phi, paths1, theta, paths2,
                                             all_vars=all_vars)
    assert len(volume1.volume) == 3
    assert len(volume2.volume) == 5

    # The metric reports floats by design (point_sim_d calls float() at the
    # boundary), so these are the exact doubles the pipeline produces, not
    # rationals: 4.5/5 and 1.9/2 are both representable without rounding.
    forward = one_way_similarity(volume1, volume2, all_vars, D)
    backward = one_way_similarity(volume2, volume1, all_vars, D)
    assert forward == 1.0              # phi's cells are all present in theta's
    assert backward == 0.9             # theta0 and theta1 have no phi twin
    assert calc_similarity_from_formulas(phi, theta, D=D) == 0.95


def test_worked_example_part2_matches_EXAMPLE_md():
    """EXAMPLE.md Part 2: bounded atoms, a disjunction, four paths.

    phi = F[0,1]((x>0 && x<2) || (x>4 && x<6))   theta = F[0,1](x>1 && x<5)

    This is the pair that exercises point_sim_d's Jaccard branch. Part 1's pair
    reaches it on no call at all -- every one of its slabs is a half-line, so
    every comparison exits at the identical-after-truncation or disjoint early
    return. Here the two breakpoint sets are disjoint ({0,2,4,6} vs {1,5}), so
    no slab of one equals a slab of the other and the ratio is the whole story.
    """
    phi = "F[0,1]((x>0 && x<2) || (x>4 && x<6))"
    theta = "F[0,1](x>1 && x<5)"
    paths1, paths2, all_vars = signal_spaces_from_definition(phi, theta)
    assert all_vars == ["x"]
    assert (len(paths1), len(paths2)) == (4, 2)   # 2 disjuncts x 2 witness instants

    D = resolve_D(None, parse(phi), parse(theta))
    assert D == 7                                 # max|con| + 1 = 6 + 1

    volume1, volume2 = build_aligned_volumes(phi, paths1, theta, paths2,
                                             all_vars=all_vars)
    assert (len(volume1.volume), len(volume2.volume)) == (16, 5)

    # The Jaccard branch itself, on the slab pair EXAMPLE.md derives by hand:
    # meet (1,2) has length 1, join (0,5) has length 5.
    assert point_sim_d([Interval(0, 2, True, True)],
                       [Interval(1, 5, True, True)], 7) == 1 / 5

    # A bounded slab pair is D-invariant -- it lies inside every legal window --
    # while the unbounded pairs in the same table drift towards 1 as D grows.
    # That contrast is the point of Part 2's "Why D matters" table.
    assert point_sim_d([Interval(0, 2, True, True)],
                       [Interval(1, 5, True, True)], 100) == 1 / 5

    score = calc_similarity_from_formulas(phi, theta, D=D)
    assert math.isclose(score, 0.4159375)         # NOT equal: 0.41593749999999996


def test_worked_example_part3_matches_EXAMPLE_md():
    """EXAMPLE.md Part 3: the L-shape, cut two ways, from real formula strings.

    tests/test_canon.py pins the same region, but builds it as hand-made boxes
    and never goes near the parser -- its L_SHAPE_1/L_SHAPE_2 constants use
    chained comparisons ("0<=x<=2") and are display labels, not input. This one
    drives the region from STL that actually parses, which is what EXAMPLE.md
    shows, so a fragment change that broke the document would fail here.

    The claim is stronger than "scores 1.0": the two decompositions share no
    box, yet canonicalise to the identical cell SET.
    """
    phi = "((x>=0 && x<=2) && (y>=0 && y<=1)) || ((x>=0 && x<=1) && (y>=1 && y<=2))"
    theta = "((x>=0 && x<=1) && (y>=0 && y<=2)) || ((x>=1 && x<=2) && (y>=0 && y<=1))"
    paths1, paths2, all_vars = signal_spaces_from_definition(phi, theta)
    assert all_vars == ["x", "y"]
    assert (len(paths1), len(paths2)) == (2, 2)

    cells1, cells2 = canonicalize(paths1), canonicalize(paths2)
    assert len(cells1) == len(cells2) == 3
    assert {cell_key(c) for c in cells1} == {cell_key(c) for c in cells2}

    D = resolve_D(None, parse(phi), parse(theta))
    before = compute_similarity(build_volume_from_paths(phi, paths1, all_vars),
                                build_volume_from_paths(theta, paths2, all_vars), D=D)
    assert before == 0.75                         # box-to-box, no canonicalisation
    assert calc_similarity_from_formulas(phi, theta, D=D) == 1.0


